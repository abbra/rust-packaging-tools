"""rust-deps packit: the .packit.yaml that releases a chain as one update.

A chain's members must move together: a consumer's build fails against the older
version of its provider.  Packit's sidetag groups do that release — each merged
change is built into one Koji side-tag in dependency order, and one Bodhi update
is filed from the tag when every build is in.  (It does not help the pull
requests: Fedora CI scratch-builds one repository against current Fedora, so the
consumer's PR is red until its provider lands; 'rust-deps sidetag' is what
checks a chain before anything merges.)
"""

from __future__ import annotations

import os
from pathlib import Path
import textwrap

from . import build
from . import config
from . import packages
from . import util

PACKIT_FILE = config.PACKIT_FILE

HEADER = (
    "# Generated by rust-deps ('rust-deps packit'); it rewrites this file from the\n"
    "# packages' build dependencies.  https://packit.dev/docs/fedora-releases-guide/"
    "releasing-multiple-packages\n"
)


def dep_edges(pkgs: list[packages.LocalPackage], root: Path) -> dict[str, set[str]]:
    """crate -> the selected crates its build needs (reading each spec once)."""
    names = {p.crate for p in pkgs}
    return {c: ds & names for c, ds in build.local_deps(pkgs, root).items()}


def components(deps: dict[str, set[str]]) -> list[set[str]]:
    """The crates that must move together: connected components of that graph,
    two or more crates each.

    One .packit.yaml carries one sidetag_group, so a crate shared by two chains
    (ciborium under several consumers) forces them into one group: releasing a
    single member of it on its own then needs '/packit koji-tag --all-branches'
    in a pull request of the others, to tag their current builds into the tag.
    """
    names = set(deps)
    groups, done = [], set()
    for start in sorted(names):
        if start in done:
            continue
        members, stack = {start}, [start]
        while stack:  # follow the edges in both directions
            crate = stack.pop()
            for other in {crate} | deps[crate] | {c for c in names if crate in deps[c]}:
                if other not in members:
                    members.add(other)
                    stack.append(other)
        done |= members
        if len(members) > 1:
            groups.append(members)
    return groups


def group_edges(
    members: set[str], deps: dict[str, set[str]]
) -> tuple[dict[str, set[str]], dict[str, set[str]]]:
    """crate -> (crates it needs, crates that need it), within one chain."""
    inside = {c: deps[c] & members for c in members}
    return inside, {c: {m for m in members if c in inside[m]} for c in members}


def yaml_list(key: str, items: list[str], indent: str) -> str:
    return (
        f"{indent}{key}:\n"
        if items
        else ""
    ) + "".join(f"{indent}  - {i}\n" for i in items)


def render(
    group: str,
    pkg: packages.LocalPackage,
    providers: list[str],
    consumers: list[str],
    others: list[str],
    top: bool,
    authors: list[str],
) -> str:
    """One package's .packit.yaml: build it into the chain's sidetag, and (for the
    chain's top) file the update once every member's build is in the tag."""
    name = pkg.rpm_name
    out = [HEADER]
    # a member with providers in the chain is also (re)triggered when one of them
    # lands in the tag, and is skipped while they are missing: the chain builds in
    # dependency order
    trigger = "commit | koji_build" if providers else "commit"
    out.append(f"jobs:\n  - job: koji_build\n    trigger: {trigger}\n")
    out.append(f"    sidetag_group: {group}\n")
    out += [
        yaml_list(k, v, "    ")
        for k, v in (("dependencies", providers), ("dependents", consumers))
        if v
    ]
    out.append(yaml_list("allowed_pr_authors", authors, "    "))
    out.append(yaml_list("allowed_committers", authors, "    "))  # direct pushes to dist-git
    out.append("    dist_git_branches:\n      - fedora-all\n")
    if top:
        # one update for the whole chain, once every member's build is in the tag.
        # No allowed_* list here: this job is triggered by the tag, not by a PR.
        out.append(
            "  - job: bodhi_update\n    trigger: koji_build\n"
            f"    sidetag_group: {group}\n"
            + yaml_list("dependencies", others, "    ")
            + "    dist_git_branches:\n      - fedora-all\n"
        )
    return "".join(out)


def cmd_packit(args) -> None:
    """Write each package's .packit.yaml, so its chain is released as one update."""
    pkgs = packages.select(args.root, args.crates, args.all)
    fas = args.fas or os.environ.get("RUST_DEPS_FAS")
    if not fas:
        util.die("give your Fedora account name with --fas (or RUST_DEPS_FAS)")
    authors = [fas, *args.allow_pr_author]
    by_name = {p.crate: p for p in pkgs}
    deps = dep_edges(pkgs, args.root)
    found = components(deps)
    if not found:
        util.info(
            "no chain of two or more of these packages: nothing to release together "
            "(each package can be updated on its own)"
        )
        return
    written = []
    for members in found:
        providers, consumers = group_edges(members, deps)
        tops = sorted(c for c in members if not consumers[c])
        # the group is named for its top; a component with several tops (two
        # consumers of one provider) is named for the first
        group = f"{by_name[tops[0]].rpm_name}-updates"
        util.info(f"== {group}: {' '.join(sorted(by_name[c].rpm_name for c in members))}")
        if len(tops) > 1:
            # one sidetag_group per package, so the chains that share a provider
            # cannot be released separately
            util.warn(
                f"{group} holds {len(tops)} unrelated tops ({', '.join(by_name[c].rpm_name for c in tops)}): "
                "they share a library, so one group covers them all and releasing one of "
                "its chains alone needs '/packit koji-tag --all-branches' in a pull request "
                "of the others, to tag their current builds into the side-tag. If that is "
                "not what you want, name the chain instead of --all (the shared library "
                "then stays out of the group)."
            )
        for crate in sorted(members, key=lambda c: by_name[c].rpm_name):
            pkg = by_name[crate]
            text = render(
                group,
                pkg,
                sorted(by_name[c].rpm_name for c in providers[crate]),
                sorted(by_name[c].rpm_name for c in consumers[crate]),
                sorted(by_name[c].rpm_name for c in members if c != crate),
                # exactly one update per group: its bodhi_update job waits for every
                # other member's build to be in the tag, so one of the tops files it
                crate == tops[0],
                authors,
            )
            if args.dry_run:
                util.info(f"   {pkg.dir / PACKIT_FILE}:")
                util.info(textwrap.indent(text, "   | "))
                continue
            existing = pkg.dir / PACKIT_FILE
            if existing.exists() and not existing.read_text().startswith("# Generated by rust-deps"):
                # someone else's configuration (pull_from_upstream, hand-written jobs):
                # not ours to replace without being asked
                util.action(
                    f"{pkg.crate}: {PACKIT_FILE} is not ours to rewrite; keep it and add the "
                    "sidetag_group/dependencies keys to its jobs, or delete it to generate one"
                )
                continue
            existing.write_text(text)
            written.append(pkg.crate)
    if written:
        util.info(
            f"wrote {PACKIT_FILE} for: {', '.join(written)}; 'dist-git' carries it into "
            "the repositories.  It releases what is merged there; a chain is still checked "
            "before merging with 'sidetag'."
        )
